"""HomeKit setup info (SRP salt + verifier) for a setup code, as main/secrets.h.

stdin: "XXX-XX-XXX/ID". argv[1]: output header. The code itself is not written: the
accessory needs only the verifier (HAP spec), and the firmware stores it in NVS once.
The verifier still allows an offline search of the 10^8 codes, so it stays as secret as
the code: local builds only, never CI or a release.
"""
import hashlib
import os
import re
import sys
from pathlib import Path

code, setup_id = sys.stdin.read().strip().split("/")
if not re.fullmatch(r"\d{3}-\d{2}-\d{3}", code) or not re.fullmatch(r"[0-9A-Z]{4}", setup_id):
    sys.exit("expected XXX-XX-XXX/ID")

# The group is the SDK's own (RFC 5054 3072-bit, g = 5), read from its source so the two
# cannot drift apart.
src = (Path(__file__).parent.parent / "components/mu_srp/mu_srp.c").read_text()
body = re.search(r"N_3072\[\] = \{(.*?)\};", src, re.S).group(1)
N = int.from_bytes(bytes(int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", body)), "big")
g = 5

salt = os.urandom(16)
inner = hashlib.sha512(b"Pair-Setup:" + code.encode()).digest()
x = int.from_bytes(hashlib.sha512(salt + inner).digest(), "big")
verifier = pow(g, x, N).to_bytes(384, "big")


def arr(b):
    return ", ".join(f"0x{v:02x}" for v in b)


out = Path(sys.argv[1])
out.write_text(
    "#pragma once\n"
    "// Generated by tools/setup_info.py; never commit.\n"
    f'#define SETUP_ID "{setup_id}"\n'
    f"#define SETUP_SALT {{ {arr(salt)} }}\n"
    f"#define SETUP_VERIFIER {{ {arr(verifier)} }}\n")
os.chmod(out, 0o600)
